export function getBlogSchema(post: {
  slug: string;
  title: string;
  excerpt?: string;
  seoDescription?: string;
  featuredImageUrl?: string;
  publishedAt?: string | null;
  createdAt?: string;
  author?: { name: string; role?: string };
}) {
  if (blogPostingSchemas[post.slug]) {
    return blogPostingSchemas[post.slug];
  }

  const encodedImage = post.featuredImageUrl
    ? post.featuredImageUrl.startsWith("http")
      ? post.featuredImageUrl
      : `https://graceandgoodwill.co.uk/_next/image?url=${encodeURIComponent(post.featuredImageUrl)}&w=1080&q=75`
    : "https://graceandgoodwill.co.uk/_next/image?url=%2Fwebsite_logo.png&w=1080&q=75";

  const date =
    (post.publishedAt ? post.publishedAt.split("T")[0] : null) ||
    (post.createdAt ? post.createdAt.split("T")[0] : null) ||
    "2026-08-21";

  return {
    "@context": "https://schema.org",
    "@type": "BlogPosting",
    mainEntityOfPage: {
      "@type": "WebPage",
      "@id": `https://graceandgoodwill.co.uk/blog/${post.slug}`,
    },
    headline: post.title,
    description: post.seoDescription || post.excerpt || "",
    image: encodedImage,
    author: {
      "@type": "Person",
      name: post.author?.name || "Aurea Neto",
    },
    publisher: {
      "@type": "Organization",
      "name": "Grace & Goodwill",
      logo: {
        "@type": "ImageObject",
        url: "https://graceandgoodwill.co.uk/_next/image?url=%2Fwebsite_logo.png&w=48&q=75",
      },
    },
    datePublished: date,
  };
}
